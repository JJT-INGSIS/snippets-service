package com.jjt.ingsis.snippets.telemetry

import com.jjt.ingsis.snippets.formattingrules.FormattingRulesChangedJob
import com.jjt.ingsis.snippets.formattingrules.FormattingScope
import com.jjt.ingsis.snippets.formattingrules.FormattingSelection
import com.jjt.ingsis.snippets.language.ProcessorRevision
import org.assertj.core.api.Assertions.assertThat
import org.junit.jupiter.api.AfterEach
import org.junit.jupiter.api.Test
import org.slf4j.MDC
import java.util.UUID

private const val NGINX_ID = "0123456789abcdef0123456789abcdef"
private const val SAME_ID_AS_UUID = "01234567-89ab-cdef-0123-456789abcdef"
private const val HIGH_BITS_ID = "ffffffffffffffff8000000000000001"
private const val RANDOM_UUID_VERSION = 4

class RequestCorrelationTest {
    @AfterEach
    fun clearContext() = MDC.clear()

    @Test
    fun `the nginx request id becomes the same 128 bits as a uuid`() {
        assertThat(requestCorrelationId(NGINX_ID)).isEqualTo(UUID.fromString(SAME_ID_AS_UUID))
        assertThat(requestCorrelationId(HIGH_BITS_ID)?.toString()?.replace("-", "")).isEqualTo(HIGH_BITS_ID)
    }

    @Test
    fun `only ids generated by nginx are used`() {
        listOf(null, "", "attacker-value", NGINX_ID.uppercase(), NGINX_ID + "0").forEach { value ->
            assertThat(requestCorrelationId(value)).describedAs(value ?: "null").isNull()
        }
    }

    @Test
    fun `a rules change inside a request carries that request as its correlation`() {
        MDC.put(REQUEST_ID, NGINX_ID)

        val job =
            FormattingRulesChangedJob.of(
                scope = FormattingScope("dev-juan", "printscript", "1.1"),
                configurationId = UUID.randomUUID(),
                selection = FormattingSelection.EMPTY,
                processor = ProcessorRevision("sha256-v1:" + "a".repeat(64)),
            )

        assertThat(job.event.correlationId).isEqualTo(UUID.fromString(SAME_ID_AS_UUID))
    }

    @Test
    fun `without a request the correlation stays random`() {
        val first = currentCorrelationId()
        val second = currentCorrelationId()

        assertThat(first).isNotEqualTo(second)
        assertThat(first.version()).isEqualTo(RANDOM_UUID_VERSION)
    }
}
